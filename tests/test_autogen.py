def test_generate_tasks_accumulates_ids_across_skills(
    fake_plugin_dir: Path, minimal_valid_task: dict[str, Any]
) -> None:
    """task_ids from earlier skills are passed to later skill calls to prevent duplicates."""
    config = AutogenConfig()
    call_systems: list[str] = []

    def capture_call(**kw: Any) -> MagicMock:
        call_systems.append(kw.get("system", ""))
        return _make_mock_response([{**minimal_valid_task, "task_id": f"task-{len(call_systems)}"}])

    with patch("coder_eval.tools.autogen.generator.anthropic.Anthropic") as mock_client_cls:
        mock_client = mock_client_cls.return_value
        mock_client.messages.create.side_effect = capture_call

        generate_tasks(fake_plugin_dir, config)  # return value not needed here

    # Second skill call's system prompt should mention the first skill's task ID
    assert "task-1" in call_systems[1]


def test_generate_tasks_continues_after_skill_failure(
    fake_plugin_dir: Path, minimal_valid_task: dict[str, Any]
) -> None:
    """A failed skill does not abort generation of remaining skills."""
    config = AutogenConfig()
    call_count = 0

    def flaky(*args: Any, **kwargs: Any) -> MagicMock:  # pyright: ignore[reportUnusedParameter]
        nonlocal call_count
        call_count += 1
        if call_count == 1:
            raise RuntimeError("simulated API error")
        return _make_mock_response([minimal_valid_task])

    with patch("coder_eval.tools.autogen.generator.anthropic.Anthropic") as mock_client_cls:
        mock_client = mock_client_cls.return_value
        mock_client.messages.create.side_effect = flaky

        result, errors = generate_tasks(fake_plugin_dir, config)

    # First skill failed, second succeeded -- one task returned, not zero
    assert len(result) == 1
    assert len(errors) == 1


def test_generate_tasks_on_skill_callback(fake_plugin_dir: Path, minimal_valid_task: dict[str, Any]) -> None:
    config = AutogenConfig()
    callbacks: list[tuple[str, int, int]] = []

    with patch("coder_eval.tools.autogen.generator.anthropic.Anthropic") as mock_client_cls:
        mock_client = mock_client_cls.return_value
        mock_client.messages.create.return_value = _make_mock_response([minimal_valid_task])

        generate_tasks(fake_plugin_dir, config, on_skill=lambda n, i, t: callbacks.append((n, i, t)))

    assert len(callbacks) == 2
    assert callbacks[0][2] == 2  # total == number of skills


