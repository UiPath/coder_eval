def test_discover_skills_raises_if_no_skills_dir(tmp_path: Path) -> None:
    with pytest.raises(ValueError, match="No 'skills/' subdirectory"):
        _discover_skills(tmp_path)


def test_discover_skills_ignores_dirs_without_skill_md(tmp_path: Path) -> None:
    skills_dir = tmp_path / "skills"
    skills_dir.mkdir()
    (skills_dir / "empty").mkdir()  # no SKILL.md
    real_skill = skills_dir / "greet"
    real_skill.mkdir()
    (real_skill / "SKILL.md").write_text("# Greet\n")
    skills = _discover_skills(tmp_path)
    assert all(s.name != "empty" for s in skills)
    assert any(s.name == "greet" for s in skills)


