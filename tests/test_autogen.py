def test_generate_tasks_calls_per_skill(fake_plugin_dir: Path, minimal_valid_task: dict[str, Any]) -> None:
    """One LLM call is made per skill, not one call for all."""
    config = AutogenConfig()

    with patch("coder_eval.tools.autogen.generator.anthropic.Anthropic") as mock_client_cls:
        mock_client = mock_client_cls.return_value
        mock_client.messages.create.return_value = _make_mock_response([minimal_valid_task])

        result, errors = generate_tasks(fake_plugin_dir, config)

    # Two skills -> two LLM calls
    assert mock_client.messages.create.call_count == 2
    assert len(result) == 2  # one task returned per skill call
    assert errors == []


def test_generate_tasks_injects_provenance_tags(fake_plugin_dir: Path, minimal_valid_task: dict[str, Any]) -> None:
    """Plugin name and skill name are added to every generated task."""
    config = AutogenConfig()

    with patch("coder_eval.tools.autogen.generator.anthropic.Anthropic") as mock_client_cls:
        mock_client = mock_client_cls.return_value
        mock_client.messages.create.return_value = _make_mock_response([minimal_valid_task])

        result, _ = generate_tasks(fake_plugin_dir, config)

