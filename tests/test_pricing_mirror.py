"""Unit tests for the generated evalboard rate table (CE065's renderer).

These cover `render_pricing` against small explicit rate cards rather than the
live table — the live table's contents are CE065's job, and asserting against
its size here would make every reprice a two-file edit, which is the coupling
the generator exists to remove.
"""

import math
import re

import pytest

from coder_eval.pricing import ModelPricing, builtin_rates
from tests.lint.pricing_mirror import (
    DELIBERATELY_UNMIRRORED,
    _assert_exemptions_are_live,
    render_pricing,
)


ORDINARY = ModelPricing(1.0, 2.0, 3.0, 4.0)
PER_REQUEST = ModelPricing(5.0, 6.0, 7.0, 8.0, per_request_billing=True)


def test_each_ts_field_carries_its_own_python_rate():
    """ORDINARY's four rates are distinct, so a swapped pair fails here rather
    than only in the evalboard's vitest job."""
    rendered = render_pricing({"plain-model": ORDINARY})
    assert ("inputPerMTok: 1.0, outputPerMTok: 2.0, cacheWritePerMTok: 3.0, cacheReadPerMTok: 4.0") in rendered


def test_per_request_rows_are_omitted_and_ordinary_ones_kept():
    rendered = render_pricing({"vendor/routed": PER_REQUEST, "plain-model": ORDINARY})
    assert '"plain-model": {' in rendered
    assert '"vendor/routed": {' not in rendered
    # The reader of the generated file is told why the row is absent.
    assert "per_request_billing" in rendered
    assert "vendor/routed" in rendered


def test_output_is_deterministic_and_sorted():
    rates = {"zeta": ORDINARY, "alpha": ORDINARY, "mid": ORDINARY}
    first = render_pricing(rates)
    assert first == render_pricing(rates)
    keys = [line.split('"')[1] for line in first.splitlines() if line.startswith('    "')]
    assert keys == sorted(keys) == ["alpha", "mid", "zeta"]


@pytest.mark.parametrize("bad", [math.inf, -math.inf, math.nan])
def test_non_finite_rate_raises_naming_the_key(bad):
    with pytest.raises(ValueError, match="broken-model"):
        render_pricing({"broken-model": ModelPricing(bad, 2.0, 3.0, 4.0)})


def test_high_precision_rate_survives_verbatim():
    rendered = render_pricing({"precise": ModelPricing(1.030776, 2.061552, 1.030776, 0.085898)})
    assert "0.085898" in rendered
    assert "1.030776" in rendered


def test_all_zero_free_model_is_emitted_not_skipped():
    """The skip predicate is `per_request_billing`, never falsiness — a free
    model is a real rate and must price as $0, not render as unpriced."""
    rendered = render_pricing({"free-model": ModelPricing(0.0, 0.0, 0.0, 0.0)})
    assert '"free-model": {' in rendered


def test_key_needing_escaping_is_emitted_as_valid_json():
    rendered = render_pricing({'weird"key\\x': ORDINARY})
    assert r'"weird\"key\\x": {' in rendered


def test_generated_header_marks_the_file_as_generated():
    rendered = render_pricing({"plain-model": ORDINARY})
    assert rendered.startswith("// generated by `make pricing-mirror` — do not edit")
    assert rendered.endswith("};\n")
    assert 'import type { Pricing } from "./pricing";' in rendered


def test_builtin_rates_is_read_only_and_populated():
    rates = builtin_rates()
    assert "claude-sonnet-5" in rates
    with pytest.raises(TypeError):
        rates["claude-sonnet-5"] = ORDINARY  # type: ignore[index]


class TestTheSecondExemptionAxis:
    """`DELIBERATELY_UNMIRRORED` — priced in Python, not priced on the frontend.

    Separate from `per_request_billing` because the two make different claims: a
    routed rate MUST NOT be mirrored (an estimate would displace a real captured
    figure), whereas these are simply not worth pricing on the board. Folding them
    into one axis is what silently widened the generated table past the hand-copy
    it replaced.
    """

    def test_an_exempted_id_is_omitted_but_still_priced_in_python(self):
        exempt = next(iter(DELIBERATELY_UNMIRRORED))
        assert exempt in builtin_rates()
        assert f'"{exempt}": {{' not in render_pricing()

    def test_the_generated_file_names_both_axes_separately(self):
        rendered = render_pricing()
        assert "per_request_billing" in rendered
        assert "DELIBERATELY_UNMIRRORED" in rendered

    def test_a_stale_exemption_fails_the_build(self):
        """The guard the deleted parity test carried, and the reason it mattered:
        an id that has left `pricing.py` silences nothing and only survives to be
        copied."""
        with pytest.raises(ValueError, match=re.escape("gpt-5.4-pro")):
            _assert_exemptions_are_live({"claude-sonnet-5": ORDINARY})

    def test_a_live_exemption_set_passes(self):
        _assert_exemptions_are_live(builtin_rates())

    def test_the_generated_table_reproduces_what_the_hand_copy_priced(self):
        """The mirror must not silently PRICE a model the frontend deliberately did
        not. Stated as the set identity rather than a literal key list, so an
        ordinary reprice stays a one-file edit and only an exemption change moves it.
        """
        rendered = render_pricing()
        keys = {line.split('"')[1] for line in rendered.splitlines() if line.startswith('    "')}
        rates = builtin_rates()
        routed = {k for k, v in rates.items() if v.per_request_billing}
        assert keys == rates.keys() - routed - DELIBERATELY_UNMIRRORED
