"""CE065 — the evalboard's rate table is generated from ``coder_eval.pricing``.

``evalboard/lib/pricing.ts`` used to carry a hand-copied mirror of the Python
rate card. Keeping a hand-copy honest needed five layers of bookkeeping: a
regex parser that re-read ``pricing.py`` at test time, a meta-guard against that
regex silently narrowing, a ``DELIBERATELY_UNMIRRORED`` exemption set, a
staleness guard for the exemption set, and a comment begging the next reader to
keep the set honest. It still shipped a real bug — ``claude-sonnet-5``,
``gpt-5.6-sol``, ``gpt-5.6-terra`` and ``gpt-5.6-luna`` sat in the exemption set
under "the evalboard never runs them" while appearing tens of thousands of times
in the run corpus, so every one of those runs rendered "—" for cost with nothing
failing.

If a *test* can read the table, a *generator* can emit it. So the table is no
longer copied: ``render_pricing()`` renders
``evalboard/lib/pricing.generated.ts`` from ``pricing.builtin_rates()``, ``make
pricing-mirror`` calls ``write()``, and CE065 (``check()``) re-renders and diffs
against disk. There is deliberately **no ``--check`` mode and no arg parser** —
CE065 *is* the checker, the same rule ``plugin_reference.py`` states.

The exemption set encoded TWO different things, and they survive differently.
That three OpenRouter models must stay unpriced so ``runs.ts``'s apportionment of
the provider's real bill still fires is a property of the RATE, so it is now data
on the rate itself (``ModelPricing.per_request_billing``), beside the rate it
qualifies; nothing has to remember it. That four heavy frontier variants are not
priced on the frontend is a property of the FRONTEND, not of the rate, so it
stays here as ``DELIBERATELY_UNMIRRORED`` — an explicit list with the same
stale-membership guard the deleted test carried, because an exemption nobody
re-reads is what shipped the bug above.

Like CE028 and CE033 this is not a ``BaseRule`` in the AST runner: it reasons
over generated text rather than one Python AST, so it is wired as a
``@pytest.mark.lint`` class in ``tests/test_custom_lint.py``.
"""

from __future__ import annotations

import json
import math
from collections.abc import Mapping
from pathlib import Path

from coder_eval.pricing import ModelPricing, builtin_rates
from tests.lint.generated import diff_all, write_all


_MIRROR_REL = "evalboard/lib/pricing.generated.ts"
_GENERATED_HEADER = "// generated by `make pricing-mirror` — do not edit"

# Priced in Python, deliberately NOT priced on the frontend: heavy frontier variants
# no harness runs, so a rate here buys nothing. Unlike ``per_request_billing`` this is
# not a fact about the rate — the rate is correct, the evalboard just has no use for
# it — which is why it lives beside the generator rather than on ``ModelPricing``.
#
# KEEP THIS SET HONEST. Membership silences the mirror for one id indefinitely, so a
# stale entry hides a live bug rather than a non-issue: `claude-sonnet-5`,
# `gpt-5.6-sol`, `gpt-5.6-terra` and `gpt-5.6-luna` sat in the predecessor of this set
# under "the evalboard never runs them" while appearing tens of thousands of times in
# the run corpus, so every one of those runs rendered "—" for cost with nothing
# failing. Before adding an id, grep the corpus for it — absence from run data is the
# ONLY justification, and it expires the moment a harness adopts the model.
# ``_assert_exemptions_are_live`` fails the build once an id leaves ``pricing.py``.
DELIBERATELY_UNMIRRORED = frozenset(
    {
        "gpt-5.4-mini",
        "gpt-5.4-nano",
        "gpt-5.4-pro",
        "gpt-5.5-pro",
    }
)


def _number(key: str, field: str, value: float) -> str:
    """A TS numeric literal for one rate, full precision preserved.

    ``repr`` round-trips every float exactly, so 0.085898 survives verbatim. It
    also emits ``inf``/``nan`` for non-finite values, which are not valid TS
    numeric literals — those fail here rather than producing a file that only
    breaks once ``tsc`` runs.
    """
    if not math.isfinite(value):
        raise ValueError(f"non-finite rate for {key!r}: {field}={value!r} cannot be rendered as TypeScript")
    return repr(float(value))


def _assert_exemptions_are_live(rates: Mapping[str, ModelPricing]) -> None:
    """Every ``DELIBERATELY_UNMIRRORED`` id must still be priced in ``pricing.py``.

    An exemption silences the mirror for one id indefinitely. Once the id leaves
    the rate card the entry silences nothing and only survives to be copied, so
    making that a build failure is what forces the set to be re-read rather than
    appended to. Carried over from the deleted parity test, which had it right.
    """
    stale = sorted(DELIBERATELY_UNMIRRORED - rates.keys())
    if stale:
        raise ValueError(
            f"DELIBERATELY_UNMIRRORED names ids no longer priced in pricing.py: {', '.join(stale)} — drop them"
        )


def render_pricing(rates: Mapping[str, ModelPricing] | None = None) -> str:
    """Render the generated TS rate table from a Python rate card.

    Two exemption axes, kept separate because they are different claims. A
    ``per_request_billing`` rate must not be mirrored (a static estimate would
    replace the captured actual per-call cost); a ``DELIBERATELY_UNMIRRORED`` id
    simply is not worth pricing on the frontend.
    """
    rates = builtin_rates() if rates is None else rates
    priced = {k: v for k, v in sorted(rates.items()) if not v.per_request_billing and k not in DELIBERATELY_UNMIRRORED}
    routed = sorted(k for k, v in rates.items() if v.per_request_billing)
    unmirrored = sorted(DELIBERATELY_UNMIRRORED & rates.keys())

    lines = [
        _GENERATED_HEADER,
        "// Source: src/coder_eval/pricing.py — regenerate with `make pricing-mirror`.",
        "",
        'import type { Pricing } from "./pricing";',
        "",
    ]
    if routed:
        lines += [
            "// Omitted (per_request_billing): the provider bills per request, so a static",
            "// rate here would replace the captured ACTUAL per-call cost with an estimate.",
            f"// {', '.join(routed)}",
        ]
    if unmirrored:
        lines += [
            "// Omitted (DELIBERATELY_UNMIRRORED in tests/lint/pricing_mirror.py): priced in",
            "// Python for the max_usd pre-flight, but no harness runs them on this board.",
            f"// {', '.join(unmirrored)}",
        ]
    lines.append("export const PRICING: Record<string, Pricing> = {")
    for key, rate in priced.items():
        lines.append(
            f"    {json.dumps(key)}: {{ "
            f"inputPerMTok: {_number(key, 'input_per_mtok', rate.input_per_mtok)}, "
            f"outputPerMTok: {_number(key, 'output_per_mtok', rate.output_per_mtok)}, "
            f"cacheWritePerMTok: {_number(key, 'cache_write_per_mtok', rate.cache_write_per_mtok)}, "
            f"cacheReadPerMTok: {_number(key, 'cache_read_per_mtok', rate.cache_read_per_mtok)} }},"
        )
    lines.append("};")
    return "\n".join(lines) + "\n"


def _rendered_files(repo_root: Path) -> dict[Path, str]:
    """The full intended content of each generated file, keyed by path."""
    _assert_exemptions_are_live(builtin_rates())
    return {repo_root / _MIRROR_REL: render_pricing()}


def write(repo_root: Path) -> list[Path]:
    """Regenerate the evalboard's rate table in place. Returns the target paths."""
    return write_all(_rendered_files(repo_root))


def check(repo_root: Path) -> dict[str, str]:
    """Unified diff per file whose generated content differs from disk (empty = clean)."""
    return diff_all(_rendered_files(repo_root))


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[2]
    for p in write(root):
        print(f"wrote {p}")
