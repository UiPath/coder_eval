"""CE032 — the plugin's bundled criteria reference is generated from the models.

An installed Claude Code plugin is copied to ``~/.claude/plugins/cache/`` without
its parent directories, so a skill cannot read ``docs/TASK_DEFINITION_GUIDE.md``
from this repository at runtime — every reference a skill needs has to ship
*inside* ``plugins/coder-eval/``. A bundled copy of the criterion vocabulary is
exactly the kind of file that drifts: a criterion gains a field, or a whole 15th
criterion lands, and the copy quietly keeps teaching the old schema to every
plugin user.

So the copy is not written by hand. The ``SuccessCriterion`` discriminated union
in ``coder_eval.models`` is the single source of truth; ``render_criteria()``
renders ``plugins/coder-eval/reference/criteria.md`` from it, ``make
plugin-reference`` calls ``write()``, and CE032 (``check()``) re-renders and diffs
against disk. There is deliberately **no ``--check`` mode and no arg parser** —
CE032 *is* the checker; a second entry point would be untested duplication.

Two rendering rules keep this small and are load-bearing:

- Fields inherited from ``BaseSuccessCriterion`` / ``LiveSuccessCriterion`` are
  documented once, in their own section, and **computed** — never a hardcoded
  name list, which would be a second declaration of the base schema. (When
  ``stop_early:`` replaced ``stop_when`` + ``max_steps_to_decide``, a hardcoded
  list would have started rendering the new field into all 14 per-criterion
  sections and leaked two dead names; the computed set absorbed it with no edit.)
- Required fields get a table with descriptions; optional fields get bare names
  only. Rendering defaults would mean handling ``default_factory`` (whose
  ``FieldInfo.default`` is ``PydanticUndefined``) and rendering types would mean
  normalizing ``X | None`` annotations — two helpers serving the half of the
  reference an authoring agent needs least. ``coder-eval plan`` and the model
  docstrings cover the rest.

Like CE026-CE031 this is not a ``BaseRule`` in the AST runner; it reasons over
Markdown and pydantic metadata, and is wired as
``tests/test_custom_lint.py::TestCE032PluginReferenceParity``.
"""

from __future__ import annotations

import difflib
import typing
from collections.abc import Sequence
from pathlib import Path

from pydantic.fields import FieldInfo

from coder_eval.models import BaseSuccessCriterion, LiveSuccessCriterion, SuccessCriterion


_GENERATED_HEADER = "<!-- generated by `make plugin-reference` — do not edit -->"
_REFERENCE_REL = "plugins/coder-eval/reference/criteria.md"


def _union_variants() -> tuple[type[BaseSuccessCriterion], ...]:
    """The concrete criterion classes in the ``SuccessCriterion`` union."""
    annotated_args = typing.get_args(SuccessCriterion)
    variants = typing.get_args(annotated_args[0])
    if not variants:
        raise ValueError(f"could not read variants off SuccessCriterion (got {annotated_args!r})")
    return variants


def _discriminator() -> str:
    """The union's discriminator field name, read off its ``Field(discriminator=...)``."""
    name = typing.get_args(SuccessCriterion)[1].discriminator
    if not isinstance(name, str):
        raise ValueError(f"SuccessCriterion declares no discriminator field name (got {name!r})")
    return name


_VARIANTS = _union_variants()
_DISCRIMINATOR = _discriminator()
# Inherited fields, documented once in their own section rather than repeated 14 times.
_LIVE_ONLY = tuple(k for k in LiveSuccessCriterion.model_fields if k not in BaseSuccessCriterion.model_fields)
_COMMON = set(BaseSuccessCriterion.model_fields) | set(_LIVE_ONLY)


def _tag(cls: type[BaseSuccessCriterion]) -> str:
    """The criterion's ``type:`` tag — the single value of its ``Literal`` narrowing."""
    args = typing.get_args(cls.model_fields[_DISCRIMINATOR].annotation)
    if len(args) != 1 or not isinstance(args[0], str):
        raise ValueError(f"{cls.__name__}.{_DISCRIMINATOR} is not a single-value Literal (got {args!r})")
    return args[0]


def _summary(cls: type) -> str:
    """The first non-blank line of the class docstring (empty when undocumented)."""
    for line in (cls.__doc__ or "").splitlines():
        if line.strip():
            return _cell(line)
    return ""


def _cell(text: str) -> str:
    """Collapse whitespace and escape pipes so a value is safe inside a table row."""
    return " ".join(text.split()).replace("|", r"\|")


def _own_fields(cls: type[BaseSuccessCriterion]) -> list[tuple[str, FieldInfo]]:
    """The criterion's own fields, in declaration order, minus the inherited ones."""
    return [(name, info) for name, info in cls.model_fields.items() if name not in _COMMON]


def _field_sections(fields: Sequence[tuple[str, FieldInfo]]) -> list[str]:
    """Render a required-fields table and an optional-field name list."""
    required = [(name, info) for name, info in fields if info.is_required()]
    optional = [name for name, info in fields if not info.is_required()]

    if not required and not optional:
        return ["No fields beyond the common ones."]

    out: list[str] = []
    if required:
        out.append("| Field | What it is |")
        out.append("| --- | --- |")
        out += [f"| `{name}` | {_cell(info.description or '')} |" for name, info in required]
    if optional:
        if required:
            out.append("")
        out.append("Optional: " + ", ".join(f"`{name}`" for name in optional))
    return out


def render_criteria(variants: Sequence[type[BaseSuccessCriterion]] = _VARIANTS) -> str:
    """Render the bundled criteria reference from the criterion models."""
    live = sorted(_tag(cls) for cls in variants if issubclass(cls, LiveSuccessCriterion))
    common = [(name, info) for name, info in BaseSuccessCriterion.model_fields.items() if name != _DISCRIMINATOR]

    lines = [
        _GENERATED_HEADER,
        "",
        "# Success criteria reference",
        "",
        "Every entry under a task's `success_criteria:` is one of the types below, selected by its",
        f"`{_DISCRIMINATOR}:` tag (the headings in this file). Generated from coder-eval's own",
        "`SuccessCriterion` model union, so it cannot drift from the schema the CLI validates against.",
        "Run `coder-eval plan <task.yaml>` for the authoritative error on anything left ambiguous here.",
        "",
        "## Common fields",
        "",
        "Accepted by every criterion type, in addition to its own fields below.",
        "",
        *_field_sections(common),
        "",
        "### Live-observable criteria only",
        "",
        "Some types can be decided from a partial, mid-run trajectory: " + ", ".join(f"`{tag}`" for tag in live) + ".",
        "Those additionally accept:",
        "",
        *_field_sections([(name, LiveSuccessCriterion.model_fields[name]) for name in _LIVE_ONLY]),
        "",
        "## Criterion types",
    ]

    for cls in sorted(variants, key=_tag):
        summary = _summary(cls)
        lines += ["", f"### `{_tag(cls)}`", ""]
        if summary:
            lines += [summary, ""]
        lines += _field_sections(_own_fields(cls))

    return "\n".join(lines).rstrip("\n") + "\n"


def _rendered_files(repo_root: Path) -> dict[Path, str]:
    """The full intended content of each generated file, keyed by path."""
    return {repo_root / _REFERENCE_REL: render_criteria()}


def write(repo_root: Path) -> list[Path]:
    """Regenerate the bundled reference in place. Returns the target paths."""
    written: list[Path] = []
    for path, text in _rendered_files(repo_root).items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
        written.append(path)
    return written


def check(repo_root: Path) -> dict[str, str]:
    """Unified diff per file whose generated content differs from disk (empty = clean)."""
    findings: dict[str, str] = {}
    for path, text in _rendered_files(repo_root).items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != text:
            diff = difflib.unified_diff(
                current.splitlines(),
                text.splitlines(),
                fromfile=f"{path} (on disk)",
                tofile=f"{path} (generated)",
                lineterm="",
            )
            findings[str(path)] = "\n".join(diff)
    return findings


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[2]
    for p in write(root):
        print(f"wrote {p}")
