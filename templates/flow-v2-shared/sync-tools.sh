#!/usr/bin/env bash
# sync-tools.sh [--source <flow-v2-repo>] [--skip-build] [--skip-install]
#
# Re-vendors the flow-v2 toolchain (fil-compiler, v1-to-v2, v2-to-v1,
# flow-run) into templates/flow-v2-shared/tools/ so the three flow-v2
# templates run without needing $FLOW_V2 to exist on the host.
#
# Run this from your flow-v2 working copy any time you change the
# compiler / converter / runner and want the change to land in the next
# coder_eval evaluation. Source defaults to $FLOW_V2 (falling back to
# $HOME/src/flow-v2).
#
# What this script does:
#   1. (Optional) `npm run build` each upstream package — pass
#      --skip-build to skip when you've already built.
#   2. Copies each package's dist/ + package.json into
#      flow-v2-shared/tools/<pkg>/. Source files (src/, tests/) are
#      not copied.
#   3. Writes a workspaces package.json at tools/ so npm resolves the
#      file: deps between the four packages via symlinks.
#   4. Runs `npm install --omit=dev` in tools/ to pull external runtime
#      deps (currently just wabt) — pass --skip-install to skip.
#
# Coding agents working in flow-v2: run this script before declaring a
# change shippable so the coder_eval templates pick up your fix.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TOOLS_DIR="$HERE/tools"

SOURCE=""
SKIP_BUILD=0
SKIP_INSTALL=0

while (( $# )); do
  case "$1" in
    --source) SOURCE="${2:?}"; shift 2 ;;
    --skip-build) SKIP_BUILD=1; shift ;;
    --skip-install) SKIP_INSTALL=1; shift ;;
    -h|--help)
      sed -n '2,22p' "$0" | sed 's/^# \{0,1\}//'
      exit 0
      ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac
done

if [[ -z "$SOURCE" ]]; then
  SOURCE="${FLOW_V2:-$HOME/src/flow-v2}"
fi

if [[ ! -d "$SOURCE" ]]; then
  echo "error: flow-v2 source not found at $SOURCE" >&2
  echo "set FLOW_V2 or pass --source <path>" >&2
  exit 1
fi

PACKAGES=(fil v1-to-v2 v2-to-v1 flow-run)

echo "==> source:  $SOURCE"
echo "==> target:  $TOOLS_DIR"

# Step 1 — build upstream packages.
if [[ "$SKIP_BUILD" == "0" ]]; then
  for pkg in "${PACKAGES[@]}"; do
    if [[ ! -d "$SOURCE/$pkg/node_modules" ]]; then
      echo "==> $pkg: installing upstream deps"
      ( cd "$SOURCE/$pkg" && npm install --silent )
    fi
    echo "==> $pkg: building"
    ( cd "$SOURCE/$pkg" && npm run build --silent )
  done
fi

# Step 2 — copy dist + package.json into tools/<pkg>/.
mkdir -p "$TOOLS_DIR"
for pkg in "${PACKAGES[@]}"; do
  src="$SOURCE/$pkg"
  dst="$TOOLS_DIR/$pkg"
  if [[ ! -d "$src/dist" ]]; then
    echo "error: $src/dist is missing — build $pkg first or rerun without --skip-build" >&2
    exit 1
  fi
  mkdir -p "$dst"
  rm -rf "$dst/dist"
  cp -R "$src/dist" "$dst/dist"
  # tsc only emits compiled JS / d.ts. Some packages also load non-TS
  # resources at runtime via `path.resolve(__dirname, '<file>')` (e.g.
  # v2-to-v1 reads src/core-definitions.json). Mirror src/*.json into
  # dist/ so those lookups resolve.
  if compgen -G "$src/src/*.json" > /dev/null 2>&1; then
    cp "$src"/src/*.json "$dst/dist/"
  fi
  # Strip devDependencies + scripts so `npm install` in tools/ doesn't
  # drag in jest/typescript/etc. for every workspace package.
  python3 - "$src/package.json" "$dst/package.json" <<'PY'
import json, sys
src, dst = sys.argv[1], sys.argv[2]
d = json.load(open(src))
d.pop("devDependencies", None)
d.pop("scripts", None)
d.pop("jest", None)
json.dump(d, open(dst, "w"), indent=2)
open(dst, "a").write("\n")
PY
done

# Step 3 — workspaces wrapper so file: deps resolve via symlinks.
cat > "$TOOLS_DIR/package.json" <<'EOF'
{
  "name": "flow-v2-tools-bundle",
  "private": true,
  "version": "0.0.0",
  "description": "Vendored flow-v2 toolchain for coder_eval templates. Generated by sync-tools.sh — do not edit by hand.",
  "workspaces": ["fil", "v1-to-v2", "v2-to-v1", "flow-run"]
}
EOF

# Step 4 — install runtime deps (wabt) + create workspace symlinks.
if [[ "$SKIP_INSTALL" == "0" ]]; then
  echo "==> tools/: npm install --omit=dev"
  ( cd "$TOOLS_DIR" && npm install --omit=dev --silent )
fi

# Summary.
echo ""
echo "vendored tools:"
for pkg in "${PACKAGES[@]}"; do
  size=$(du -sh "$TOOLS_DIR/$pkg/dist" 2>/dev/null | awk '{print $1}')
  printf "  %-12s %s\n" "$pkg" "$size"
done
if [[ -d "$TOOLS_DIR/node_modules" ]]; then
  total=$(du -sh "$TOOLS_DIR" 2>/dev/null | awk '{print $1}')
  echo "  tools/ total (incl. node_modules): $total"
fi
