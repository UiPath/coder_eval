"""Autogen command -- generate evaluation tasks from a plugin directory."""

from __future__ import annotations

import asyncio
from pathlib import Path

import typer
from pydantic import ValidationError

from coder_eval.cli.console import console
from coder_eval.config import Settings
from coder_eval.models import AgentConfig, ExperimentDefinition
from coder_eval.models.enums import AgentKind
from coder_eval.tools.autogen.config import AutogenConfig
from coder_eval.tools.autogen.generator import generate_experiment, generate_tasks, task_to_yaml
from coder_eval.tools.autogen.validator import validate_tasks


def autogen_command(
    plugins: Path = typer.Argument(  # noqa: B008
        ...,
        help="Plugin directory containing skills/ (e.g. ./uipath-coded-agents)",
    ),
    output: Path = typer.Argument(  # noqa: B008
        ...,
        help="Output directory for generated task YAML files",
    ),
    coverage: str = typer.Option(
        "golden",
        "--coverage",
        "-c",
        help="Coverage level: quick (1/skill) | golden (2-3/skill) | comprehensive (3-5/skill)",
    ),
    model: str = typer.Option(
        "claude-sonnet-4-6",
        "--model",
        "-m",
        help="Anthropic model used to generate tasks",
    ),
    tags: str | None = typer.Option(
        None,
        "--tags",
        help="Extra comma-separated tags added to every generated task",
    ),
    overwrite: bool = typer.Option(
        False,
        "--overwrite",
        help="Overwrite existing task files in the output directory",
    ),
    proxy: bool | None = typer.Option(
        None,
        "--proxy/--no-proxy",
        help="Override LLM Gateway proxy setting from .env (LLMGW_PROXY_ENABLED)",
    ),
) -> None:
    """Generate evaluation tasks from a Claude Code plugin directory.

    Reads skill definitions from PLUGINS/skills/ and uses an LLM to produce
    task YAML files in OUTPUT. One focused LLM call is made per skill, so
    progress is shown as each skill completes.

    Each generated task is automatically tagged with the plugin name and skill
    name (e.g. uipath-coded-agents, skill-build) for easy filtering later.

    Examples:

        coder-eval tools autogen ./uipath-coded-agents ./tasks/generated

        coder-eval tools autogen ./uipath-coded-agents ./tasks/generated --coverage comprehensive

        coder-eval tools autogen ./uipath-coded-agents ./tasks/generated --model claude-opus-4-6 --overwrite
    """
    if not plugins.is_dir():
        console.print(f"[red]Plugin directory not found: {plugins}[/red]")
        raise typer.Exit(1)

    if coverage not in ("quick", "golden", "comprehensive"):
        console.print(f"[red]--coverage must be one of: quick, golden, comprehensive (got {coverage!r})[/red]")
        raise typer.Exit(1)

    extra_tags = [t.strip() for t in tags.split(",")] if tags else []
    user_tags = list(dict.fromkeys(["autogenerated", *extra_tags]))

    # Initialize settings and override proxy if needed
    settings = Settings()
    if proxy is not None:
        settings.llmgw_proxy_enabled = proxy

    config = AutogenConfig(
        agent=AgentConfig(type=AgentKind.CLAUDE_CODE),
        generator_model=model,
        coverage=coverage,  # type: ignore[arg-type]
        tags=user_tags,
        overwrite=overwrite,
    )

    asyncio.run(_run_autogen(plugins, output, config, settings))


async def _run_autogen(
    plugins: Path,
    output: Path,
    config: AutogenConfig,
    settings: Settings,
) -> None:
    """Async entry point — keeps the event loop alive so the proxy server can serve requests."""
    proxy_port: int | None = None
    llmgw_proxy = None

    if settings.llmgw_proxy_enabled:
        from coder_eval.proxy import LLMGatewayProxy
        from coder_eval.proxy.config import ProxyConfig

        try:
            proxy_config = ProxyConfig(
                llmgw_url=settings.llmgw_url or "",
                client_id=settings.llmgw_client_id or "",
                client_secret=settings.llmgw_client_secret or "",
                org_id=settings.llmgw_semantic_org_id or "",
                tenant_id=settings.llmgw_semantic_tenant_id or "",
                requesting_product=settings.llmgw_requesting_product or "",
                requesting_feature=settings.llmgw_requesting_feature or "",
                user_id=settings.llmgw_semantic_user_id or "",
                timeout_seconds=settings.llmgw_timeout_seconds,
                vendor=settings.llmgw_proxy_vendor,
                api_flavor=settings.llmgw_proxy_api_flavor,
                task_id="autogen",
            )
            llmgw_proxy = LLMGatewayProxy(proxy_config)
            proxy_port = await llmgw_proxy.start()
            console.print(f"[dim]LLM Gateway proxy started on port {proxy_port}[/dim]\n")
        except Exception as exc:
            console.print(f"[red]Failed to start LLM Gateway proxy: {exc}[/red]")
            raise typer.Exit(1) from exc

    tasks_dir = output / "tasks"
    experiments_dir = output / "experiments"
    tasks_dir.mkdir(parents=True, exist_ok=True)
    experiments_dir.mkdir(parents=True, exist_ok=True)

    console.print(f"\n[bold]Autogen[/bold] -- {plugins.resolve().name}")
    console.print(f"  Coverage  : [yellow]{config.coverage}[/yellow]")
    console.print(f"  Model     : [yellow]{config.generator_model}[/yellow]")
    console.print(f"  Output    : [yellow]{output}[/yellow]\n")

    def on_skill(skill_name: str, idx: int, total: int) -> None:
        console.print(f"  [{idx}/{total}] generating [cyan]{skill_name}[/cyan]...")

    try:
        # Run sync LLM calls in a thread so the proxy event loop stays free
        loop = asyncio.get_running_loop()
        raw_tasks, skill_errors = await loop.run_in_executor(
            None,
            lambda: generate_tasks(
                plugins,
                config,
                output_dir=tasks_dir,
                on_skill=on_skill,
                proxy_port=proxy_port,
            ),
        )
    except ValueError as exc:
        console.print(f"[red]{exc}[/red]")
        raise typer.Exit(1) from exc
    finally:
        if llmgw_proxy:
            await llmgw_proxy.stop()

    for skill_name, exc in skill_errors:
        console.print(f"  [yellow]![/yellow]  skill [cyan]{skill_name}[/cyan] failed: {exc}")

    console.print(f"\n[green]✓[/green] Received {len(raw_tasks)} task(s) from LLM\n")

    # Validate
    valid_tasks, errors = validate_tasks(raw_tasks)

    for _, err_msg in errors:
        console.print(f"  [yellow]![/yellow]  Skipped (invalid): {err_msg}")

    if not valid_tasks:
        console.print("[red]No valid tasks generated.[/red]")
        raise typer.Exit(1)

    # Write -- deduplicate task_ids within this batch
    written = 0
    skipped = 0
    seen_ids: set[str] = set()

    for task in valid_tasks:
        if task.task_id in seen_ids:
            console.print(f"  [yellow]dup[/yellow]  {task.task_id}.yaml (duplicate task_id in batch)")
            skipped += 1
            continue
        seen_ids.add(task.task_id)

        filename = f"{task.task_id}.yaml"
        out_path = tasks_dir / filename

        if out_path.exists() and not config.overwrite:
            console.print(f"  [dim]skip[/dim] {filename}")
            skipped += 1
            continue

        out_dict = task.model_dump(mode="json", exclude_none=True)
        out_path.write_text(task_to_yaml(out_dict))
        console.print(f"  [green]✓[/green]  {filename}")
        written += 1

    # Summary
    console.print(f"\n[bold]Done.[/bold] Wrote {written} task(s), skipped {skipped}.")
    if errors:
        console.print(f"[yellow]{len(errors)} task(s) failed validation.[/yellow]")

    if written:
        experiment_dict = generate_experiment(plugins, config)

        # Validate the generated experiment against the Pydantic schema
        try:
            ExperimentDefinition.model_validate(experiment_dict)
        except ValidationError as exc:
            console.print(f"[red]Generated experiment failed validation: {exc}[/red]")
            raise typer.Exit(1) from exc

        experiment_id = experiment_dict["experiment_id"]
        experiment_path = experiments_dir / f"{experiment_id}.yaml"
        experiment_path.write_text(task_to_yaml(experiment_dict))
        console.print(f"\n[green]✓[/green]  Experiment: {experiment_path}")
        console.print("\nRun generated tasks:")
        console.print(f"  [cyan]coder-eval run {tasks_dir}/*.yaml -e {experiment_path}[/cyan]")
