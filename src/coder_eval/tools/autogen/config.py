"""Autogen configuration models."""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field

from coder_eval.models import AgentConfig, AgentKind


class AutogenConfig(BaseModel):
    """Configuration for the autogen task generator."""

    agent: AgentConfig = Field(
        default_factory=lambda: AgentConfig(type=AgentKind.CLAUDE_CODE),
        description="Agent configuration to embed in generated tasks",
    )
    generator_model: str = Field(
        default="claude-sonnet-4-6",
        description="Anthropic model used to generate tasks",
    )
    coverage: Literal["quick", "golden", "comprehensive"] = Field(
        default="golden",
        description="Coverage level -- quick: 1 task/skill, golden: 2-3, comprehensive: 3-5",
    )
    tags: list[str] = Field(
        default_factory=lambda: ["autogenerated"],
        description="Tags added to every generated task",
    )
    overwrite: bool = Field(
        default=False,
        description="Whether to overwrite existing task files in the output directory",
    )
